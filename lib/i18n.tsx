const dicts: Record<Lang, Dict> = { fr, en };

type LangState = { lang: Lang; t: Dict; setLang: (l: Lang) => void };
const LangContext = createContext<LangState>({ lang: 'fr', t: fr, setLang: () => {} });

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>('fr');

  useEffect(() => {
    AsyncStorage.getItem(KEY)
      .then((v) => {
        if (v === 'fr' || v === 'en') setLangState(v);
      })
      .catch(() => {});
  }, []);

  // Sur le web : langue de la page → bonne prononciation du lecteur d'écran
  useEffect(() => {
    if (Platform.OS === 'web' && typeof document !== 'undefined') document.documentElement.lang = lang;
  }, [lang]);

  function setLang(l: Lang) {
    setLangState(l);
    AsyncStorage.setItem(KEY, l).catch(() => {});
  }

  return <LangContext.Provider value={{ lang, t: dicts[lang], setLang }}>{children}</LangContext.Provider>;
}

export function useT() {
  return useContext(LangContext).t;
}

export function useLang() {
  return useContext(LangContext);
}

// Contenu de la base : version anglaise si elle existe, sinon le français
export function pick(lang: Lang, fr: string | null | undefined, en: string | null | undefined) {
  return (lang === 'en' && en ? en : fr) ?? '';
}
